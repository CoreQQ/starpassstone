export const AGENT_LIST = Object.values(AGENTS);

export function agentByName(name: string): AgentDef | undefined {
  const n = name.trim().toLowerCase();
  return AGENT_LIST.find(
    (a) => a.name.toLowerCase() === n || a.id === n,
  );
}

// Общая часть системного промпта: контекст бизнеса, команда, база знаний, задачи.
export function buildSystemPrompt(agent: AgentDef): string {
  const colleagues = AGENT_LIST.filter((a) => a.id !== agent.id)
    .map((a) => `- ${a.name} (${a.role})`)
    .join("\n");

  const lessons = store.recentLessons(15);
  const lessonsBlock = lessons.length
    ? lessons.map((l) => `- [${l.agent}] ${l.lesson}`).join("\n")
    : "(пока пусто)";

  const tasks = store.openTasks(20);
  const tasksBlock = tasks.length
    ? tasks
        .map((t) => `- #${t.id} [${t.priority}] ${t.title} (поставил: ${t.createdBy})`)
        .join("\n")
    : "(нет открытых задач)";

  return [
    agent.persona,
    "",
    `О бизнесе: ${config.businessProfile}`,
    `Владелец бизнеса — ${config.ownerName}. Вы работаете в общей Telegram-группе с ним.`,
    "",
    "Твои коллеги-агенты (можешь обращаться к ним через инструмент ask_agent):",
    colleagues,
    "",
    "Общая база знаний команды (уроки, которые записали все агенты — учитывай их в работе):",
    lessonsBlock,
    "",
    "Открытые задачи владельца:",
    tasksBlock,
    "",
    "Правила:",
    "- Отвечай по-русски (кроме текстов для клиентов/рекламы — они на языке рынка).",
    "- Пиши обычным текстом без Markdown-разметки (без **, ##, таблиц) — это Telegram.",
    "- Будь кратким и конкретным: списки, цифры, готовые формулировки.",
    "- Если узнал что-то полезное для команды (что сработало, что нет, важный факт о рынке/клиентах) — сохрани урок через save_lesson, чтобы коллеги учились на твоём опыте.",
    "- Если владельцу нужно что-то сделать (позвонить, оплатить, решить) — поставь задачу через create_task.",
    "- Если вопрос ближе к зоне коллеги — спроси его через ask_agent и включи его ответ в свой.",
    "- Не выдумывай факты о ценах и компаниях: если не знаешь и нет поиска — так и скажи.",
  ].join("\n");
}
