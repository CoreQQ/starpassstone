export const ASSISTANT: AgentDef = {
  id: "assistant",
  name: "Starpass",
  emoji: "🤖",
  role: "универсальный ассистент бизнеса",
  webSearch: true,
};

export const AGENTS: Record<AgentId, AgentDef> = { assistant: ASSISTANT };
