import { config } from "./config.js";
import { store } from "./store.js";

export type AgentId = "assistant";

export interface AgentDef {
  id: AgentId;
  name: string; // имя в чате
  emoji: string;
  role: string; // короткое описание роли
  webSearch: boolean; // давать ли поиск в интернете
}

