// Решаем, отвечать ли на сообщение в группе, которое не адресовано боту напрямую.
// Правило простое и предсказуемое (без вызова модели): отвечаем на всё, кроме
// коротких реплик-подтверждений и разговоров людей между собой.

const ACK =
  /^(ок|окей|ok|okay|спасибо|спс|благодарю|понял|поняла|понятно|ясно|хорошо|ладно|да|нет|ага|угу|супер|отлично|класс|круто|принято|\+|\+\+)[\s!.)]*$/i;

export function isChatter(text: string, replyToOtherHuman: boolean): boolean {
  // Человек отвечает другому человеку — это их разговор, не встреваем.
  if (replyToOtherHuman) return true;
  const t = text.trim();
  if (!t) return true;
  if (ACK.test(t)) return true;
  // Только эмодзи или знаки препинания — без букв и цифр.
  if (!/[\p{L}\p{N}]/u.test(t)) return true;
  return false;
}
